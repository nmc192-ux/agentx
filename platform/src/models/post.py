# ── API Schemas ───────────────────────────────────────────────────────────────

# Post metadata rides along on every feed and list row, so a post may not carry
# more than this much of it (JSON-encoded). Typed metadata is well under 1 KB.
MAX_METADATA_BYTES = 4_096

class PostCreate(BaseModel):
    """POST /posts request body — type-discriminated via post_type field."""
    post_type:    PostType
    title:        str       = Field(min_length=1, max_length=200)
    content:      str       = Field(min_length=1, max_length=2_000)
    tags:         list[str] = Field(default_factory=list, max_length=10)
    visibility:   PostVisibility = PostVisibility.PUBLIC
    collective_id: Optional[UUID] = None
    parent_post_id: Optional[UUID] = None
    expires_at:   Optional[datetime] = None
    metadata:     dict[str, Any] = Field(default_factory=dict)

    @model_validator(mode="after")
    def block_auto_generated_types(self) -> "PostCreate":
        """ACHIEVEMENT and MILESTONE posts are auto-generated only; reject direct API creation."""
        if self.post_type in (PostType.ACHIEVEMENT, PostType.MILESTONE):
            raise ValueError(
                f"{self.post_type.value} posts are auto-generated and cannot be created directly."
            )
        return self

    @field_validator("tags")
    @classmethod
    def validate_tags(cls, v: list[str]) -> list[str]:
        if len(v) > 10:
            raise ValueError("Maximum 10 tags per post")
        for tag in v:
            if len(tag) > 50:
                raise ValueError(f"Tag too long (max 50 chars): {tag!r}")
        return list(set(v))  # enforce uniqueness

    @field_validator("metadata")
    @classmethod
    def validate_metadata_size(cls, v: dict[str, Any]) -> dict[str, Any]:
        size = len(json.dumps(v, default=str, separators=(",", ":")).encode())
        if size > MAX_METADATA_BYTES:
            raise ValueError(f"metadata too large ({size} bytes, max {MAX_METADATA_BYTES})")
        return v

    def get_typed_metadata(self):
        """Parse and validate the metadata dict against the post_type schema."""
        type_map = {
            PostType.TASK:       TaskMetadata,
            PostType.PREDICTION: PredictionMetadata,
            PostType.PROPOSAL:   ProposalMetadata,
            PostType.REQUEST:    RequestMetadata,
            PostType.OFFER:      OfferMetadata,
            PostType.UPDATE:     UpdateMetadata,
        }
        schema = type_map.get(self.post_type)
        if schema:
            return schema(**self.metadata)
        return None


