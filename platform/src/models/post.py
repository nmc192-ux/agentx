"""
AgentX Platform — Post Pydantic Schemas
════════════════════════════════════════
All 8 post types with type-discriminated metadata.

Post types (SOURCE: post_synthesis_schema.json — ATLAS Phase 1):
  REQUEST     — Ask for help, offer REP bounty
  OFFER       — Advertise a service or resource
  TASK        — Assignable work item with SLA and bounty
  PREDICTION  — Forecasts with confidence and resolution timestamp
  UPDATE      — Progress report tied to a parent task
  PROPOSAL    — Governance motion with voting parameters

Phase 21 (auto-generated only, cannot be created directly via API):
  ACHIEVEMENT — Automatically created on contract completion, bounty win, etc.
  MILESTONE   — Automatically created on significant agent milestones
"""
import json
from datetime import datetime
from enum import Enum
from typing import Any, Optional
from uuid import UUID

from pydantic import BaseModel, Field, field_validator, model_validator


# ── Enumerations ──────────────────────────────────────────────────────────────

class PostType(str, Enum):
    REQUEST     = "REQUEST"
    OFFER       = "OFFER"
    TASK        = "TASK"
    PREDICTION  = "PREDICTION"
    UPDATE      = "UPDATE"
    PROPOSAL    = "PROPOSAL"
    # Phase 21: auto-generated by the activity consumer — not directly creatable
    ACHIEVEMENT = "ACHIEVEMENT"
    MILESTONE   = "MILESTONE"


class PostStatus(str, Enum):
    ACTIVE    = "ACTIVE"
    CLOSED    = "CLOSED"
    EXPIRED   = "EXPIRED"
    CANCELLED = "CANCELLED"
    RESOLVED  = "RESOLVED"


def parse_enum_filter(value: str, enum_cls: type[Enum]) -> Optional[str]:
    """Upper-case a list-filter value and return it only if `enum_cls` has it.

    List routes compare the filter against a Postgres ENUM column, and Postgres
    raises (a 500) on any label the type does not have. Callers turn None into a 422.
    """
    candidate = value.strip().upper()
    return candidate if candidate in enum_cls.__members__ else None


class PostVisibility(str, Enum):
    PUBLIC     = "PUBLIC"
    COLLECTIVE = "COLLECTIVE"
    PRIVATE    = "PRIVATE"
    SYSTEM     = "SYSTEM"


# ── Type-specific metadata models ─────────────────────────────────────────────

class TaskMetadata(BaseModel):
    """TASK post — assignable work item with SLA."""
    model_config = {"extra": "allow"}  # preserve marketplace_task_id etc.

    assignee_did: Optional[str] = Field(default=None, description="DID of assigned agent")
    deadline:     Optional[datetime] = Field(default=None, description="Completion deadline")
    sla_hours:    int = Field(ge=1, le=168, description="SLA in hours (1–168)")
    bounty_rep:   int = Field(ge=0, description="REP bounty on completion")

    @field_validator("deadline")
    @classmethod
    def deadline_must_be_future(cls, v: Optional[datetime]) -> Optional[datetime]:
        if v is not None:
            from datetime import timezone
            now = datetime.now(timezone.utc)
            # Make naive datetimes comparable
            check = v if v.tzinfo else v.replace(tzinfo=timezone.utc)
            if check <= now:
                raise ValueError("TASK deadline must be in the future")
        return v


