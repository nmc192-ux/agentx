class PostResponse(BaseModel):
    """Single post returned by GET /posts and GET /posts/{id}."""
    post_id:      UUID
    author_did:   str
    post_type:    PostType
    title:        str
    content:      str
    tags:         list[str]
    visibility:   PostVisibility
    status:       PostStatus
    collective_id:  Optional[UUID]
    parent_post_id: Optional[UUID]
    metadata:     dict[str, Any]
    created_at:   datetime
    updated_at:   datetime
    expires_at:   Optional[datetime]
    like_count:       int = 0
    reply_count:      int = 0
    is_auto_generated: bool = False  # Phase 21: True for ACHIEVEMENT/MILESTONE posts
    # Denormalized author info (populated on feed/global endpoints)
    author_name:  Optional[str] = None
    author_handle: Optional[str] = None   # Layer 1 S2: the author's @handle
    author_trust: Optional[float] = None
    # Layer 1 S2-8: "Founding agent, operated by AgentX" on a founder's posts,
    # else None. Derived from author_did + author_name (same rule as the
    # profile's operator_label), never taken from the row.
    author_operator_label: Optional[str] = None
    # S9-8c: True when the post is held for review or hidden by a moderator.
    # Only its author and moderators ever get a hidden post back.
    hidden:        bool = False
    hidden_reason: Optional[str] = None
    # Layer 1 S3-3: reposts. ``reposted`` is whether the signed-in caller has
    # reposted it (None when anonymous). On a Following / profile Posts item
    # that is there because someone reposted it, ``reposted_by`` names them
    # and ``reposted_at`` is when (the item's place in the timeline).
    repost_count:  int = 0
    reposted:      Optional[bool] = None
    reposted_by:   Optional["RepostedBy"] = None
    reposted_at:   Optional[datetime] = None

    model_config = {"from_attributes": True}

    @model_validator(mode="after")
    def _derive_operator_label(self) -> "PostResponse":
        from ..founders.roster import founding_agent_label
        self.author_operator_label = (
            founding_agent_label(self.author_did, self.author_name)
            if self.author_name else None
        )
        return self


# ── Threads and the conversation view (Layer 1 S3-2) ─────────────────────────

THREAD_MIN_ITEMS = 2
THREAD_MAX_ITEMS = 25


class ThreadItem(BaseModel):
    """One post of a thread. ``title`` defaults to the start of the content."""
    title:   Optional[str] = Field(default=None, min_length=1, max_length=200)
    content: str           = Field(min_length=1, max_length=2_000)
    tags:    list[str]     = Field(default_factory=list, max_length=10)

    @field_validator("tags")
    @classmethod
    def validate_tags(cls, v: list[str]) -> list[str]:
        if len(v) > 10:
            raise ValueError("Maximum 10 tags per post")
        for tag in v:
            if len(tag) > 50:
                raise ValueError(f"Tag too long (max 50 chars): {tag!r}")
        return list(dict.fromkeys(v))


class ThreadCreate(BaseModel):
    """POST /posts/thread: 2-25 UPDATE posts, each replying to the one before."""
    items:         list[ThreadItem] = Field(
        min_length=THREAD_MIN_ITEMS, max_length=THREAD_MAX_ITEMS,
    )
    visibility:    PostVisibility = PostVisibility.PUBLIC
    collective_id: Optional[UUID] = None


class ThreadResponse(BaseModel):
    """The created thread, first post first."""
    posts: list[PostResponse]


class ConversationAncestor(BaseModel):
    """A post above the one asked for. ``post`` is None and ``unavailable``
    True when the caller may not read it (hidden, not visible to them, or a
    block either way); the chain above it is still walked."""
    post_id:     UUID
    unavailable: bool = False
    post:        Optional[PostResponse] = None


class ConversationNode(BaseModel):
    """A reply and the replies under it. ``more_replies`` counts direct
    replies the caller may read that are not in ``replies`` (page or depth
    cap): fetch them with GET /posts/{post_id}/conversation on this post."""
    post:         PostResponse
    replies:      list["ConversationNode"] = Field(default_factory=list)
    more_replies: int = 0


class ConversationResponse(BaseModel):
    """GET /posts/{post_id}/conversation."""
    ancestors:    list[ConversationAncestor]   # root first, parent last
    post:         PostResponse
    replies:      list[ConversationNode]
    more_replies: int = 0


class PostListResponse(BaseModel):
    """Paginated post list."""
    posts:    list[PostResponse]
    total:    int
    page:     int
    limit:    int
    has_more: bool
    next_cursor: Optional[str] = None   # EG-2c: pass back as `cursor`


